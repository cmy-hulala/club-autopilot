_PATS = [(re.compile(p), _py_repl(r)) for p, r in PATTERNS]
_KEYS = sorted(PHRASES, key=len, reverse=True)
_BIG = re.compile("|".join(re.escape(k) for k in _KEYS))
_PUN = re.compile("|".join(re.escape(k) for k in PUNCT))


def translate(text: str, lang: str = "en") -> str:
    """Same rules as the browser: patterns, phrases (longest first), punctuation, tidy spaces."""
    if lang != "en" or not text or not re.search(r"[\u3000-\u303f\u3400-\u9fff\uff00-\uffef]", text):
        return text
    lead = text[: len(text) - len(text.lstrip())]
    trail = text[len(text.rstrip()):]
    t = text.strip()
    for rx, rep in _PATS:
        t = rx.sub(rep, t)
    t = _BIG.sub(lambda m: PHRASES[m.group(0)], t)
    t = _PUN.sub(lambda m: PUNCT[m.group(0)], t)
    t = re.sub(r" {2,}", " ", t)
    t = re.sub(r" ([,.;:)])", r"\1", t)
    t = t.replace("( ", "(").strip()
    return lead + t + trail


def payload() -> str:
    """JSON for the page (safe inside <script type=application/json>)."""
    data = {"patterns": PATTERNS, "phrases": PHRASES, "punct": PUNCT}
    return json.dumps(data, ensure_ascii=False).replace("</", "<\\/")


